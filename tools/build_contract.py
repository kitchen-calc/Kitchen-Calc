import re

KEEP_RE = re.compile(r"^(нет|да|не имеет|перечень.*|имеет.*|нет,.*|[\d,.\u2013\- ]+)$")


def tokens(text):
    """Режет текст на куски: ("t", текст) / ("b", подчёркивания, подпись|None) / ("c", подпись).
    [___]  -> линия для вписывания; [Описание] -> линия + мелкая подпись (Описание); {дата} -> только подпись;
    [75], [нет] и т. п. (готовые значения и варианты) остаются в скобках как есть."""
    out, pos = [], 0
    for m in re.finditer(r"\[([^\]]*)\]|\{([^}]*)\}", text):
        if m.start() > pos:
            out.append(("t", text[pos:m.start()]))
        pos = m.end()
        if m.group(2) is not None:
            out.append(("c", m.group(2)))
            continue
        inner = m.group(1).strip()
        if re.fullmatch(r"_*", inner):
            out.append(("b", "_" * max(4, len(inner) + 2), None))
        elif KEEP_RE.match(inner):
            out.append(("t", "[" + inner + "]"))
        else:
            out.append(("b", "_" * (11 if inner == "подпись" else 16), inner))
    if pos < len(text):
        out.append(("t", text[pos:]))
    return out


