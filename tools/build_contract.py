def build_pdf(path):
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_CENTER, TA_JUSTIFY
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import cm
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    from reportlab.platypus import KeepTogether, PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    pdfmetrics.registerFont(TTFont("TNR", os.path.join(FONTS, "times.ttf")))
    pdfmetrics.registerFont(TTFont("TNR-B", os.path.join(FONTS, "timesbd.ttf")))
    pdfmetrics.registerFont(TTFont("TNR-I", os.path.join(FONTS, "timesi.ttf")))
    pdfmetrics.registerFontFamily("TNR", normal="TNR", bold="TNR-B", italic="TNR-I", boldItalic="TNR-B")

    base = ParagraphStyle("base", fontName="TNR", fontSize=10.5, leading=13.6, spaceAfter=4.5, alignment=TA_JUSTIFY)
    title = ParagraphStyle("title", parent=base, fontName="TNR-B", fontSize=14, leading=18, alignment=TA_CENTER, spaceAfter=2, spaceBefore=4)
    sub = ParagraphStyle("sub", parent=base, fontName="TNR-B", alignment=TA_CENTER, spaceAfter=8)
    head = ParagraphStyle("head", parent=base, fontName="TNR-B", alignment=TA_CENTER, spaceBefore=9, spaceAfter=3, keepWithNext=True)
    note = ParagraphStyle("note", parent=base, fontName="TNR-I", fontSize=9, leading=11.5, spaceAfter=8)
    cell = ParagraphStyle("cell", parent=base, fontSize=9.5, leading=11.5, spaceAfter=0, alignment=0)
    cellb = ParagraphStyle("cellb", parent=cell, fontName="TNR-B")

    def esc(s):
        return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

    story = []
    for blk in CONTRACT:
        kind = blk[0]
        if kind == "title":
            story.append(Paragraph(esc(blk[1]), title))
        elif kind == "sub":
            story.append(Paragraph(esc(blk[1]), sub))
        elif kind == "row":
            t = Table([[Paragraph(esc(blk[1]), cell), Paragraph(esc(blk[2]), ParagraphStyle("r", parent=cell, alignment=2))]],
                      colWidths=[8.5 * cm, 8.5 * cm])
            t.setStyle(TableStyle([("LEFTPADDING", (0, 0), (-1, -1), 0), ("RIGHTPADDING", (0, 0), (-1, -1), 0)]))
            story.append(t)
            story.append(Spacer(1, 4))
        elif kind == "note":
            story.append(Paragraph(esc(blk[1]), note))
        elif kind == "h":
            story.append(Paragraph(esc(blk[1]), head))
        elif kind == "p":
            story.append(Paragraph(esc(blk[1]), base))
        elif kind == "table":
            spec = blk[1]
            data = [[Paragraph(esc(h), cellb) for h in spec["header"]]]
            for row in spec["rows"]:
                data.append([Paragraph(esc(v) if v else "&nbsp;", cell) for v in row])
            t = Table(data, colWidths=[w * cm for w in spec["cols"]], repeatRows=1)
            t.setStyle(TableStyle([
                ("GRID", (0, 0), (-1, -1), 0.5, colors.Color(.35, .35, .35)),
                ("BACKGROUND", (0, 0), (-1, 0), colors.Color(.92, .9, .85)),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]))
            story.append(KeepTogether([t]) if len(spec["rows"]) < 12 else t)
            story.append(Spacer(1, 8))
        elif kind == "pagebreak":
            story.append(PageBreak())

    def footer(canvas, doc_):
        canvas.saveState()
        canvas.setFont("TNR", 9)
        canvas.drawCentredString(A4[0] / 2, 1.0 * cm, str(canvas.getPageNumber()))
        canvas.restoreState()

    pdf = SimpleDocTemplate(path, pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm, topMargin=1.8 * cm, bottomMargin=1.8 * cm,
                            title="Договор на изготовление, доставку и установку мебели (шаблон)", author="Kitchen Calc")
    pdf.build(story, onFirstPage=footer, onLaterPages=footer)


