def build_docx(path):
    from docx import Document
    from docx.enum.table import WD_TABLE_ALIGNMENT
    from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_BREAK, WD_TAB_ALIGNMENT
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from docx.shared import Cm, Pt

    doc = Document()
    sec = doc.sections[0]
    sec.page_width, sec.page_height = Cm(21), Cm(29.7)
    sec.left_margin = sec.right_margin = Cm(2)
    sec.top_margin, sec.bottom_margin = Cm(1.8), Cm(1.8)

    st = doc.styles["Normal"]
    st.font.name = "Times New Roman"
    st.font.size = Pt(11)
    rpr = st.element.get_or_add_rPr()
    fonts = rpr.find(qn("w:rFonts"))
    if fonts is None:
        fonts = OxmlElement("w:rFonts")
        rpr.append(fonts)
    for a in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        fonts.set(qn(a), "Times New Roman")
    st.paragraph_format.space_after = Pt(5)
    st.paragraph_format.line_spacing = 1.08

    def para(text, bold=False, italic=False, align=None, size=None, space_before=0, space_after=None, keep=False):
        p = doc.add_paragraph()
        r = p.add_run(text)
        r.bold, r.italic = bold, italic
        if size:
            r.font.size = Pt(size)
        if align is not None:
            p.alignment = align
        if space_before:
            p.paragraph_format.space_before = Pt(space_before)
        if space_after is not None:
            p.paragraph_format.space_after = Pt(space_after)
        if keep:
            p.paragraph_format.keep_with_next = True
        return p

    def table(spec):
        cols = spec["cols"]
        t = doc.add_table(rows=1, cols=len(cols))
        t.style = "Table Grid"
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        t.autofit = False
        for i, h in enumerate(spec["header"]):
            c = t.rows[0].cells[i]
            c.text = ""
            r = c.paragraphs[0].add_run(h)
            r.bold = True
            r.font.size = Pt(10)
        for row in spec["rows"]:
            cells = t.add_row().cells
            for i, v in enumerate(row):
                cells[i].text = ""
                r = cells[i].paragraphs[0].add_run(v)
                r.font.size = Pt(10)
        for row in t.rows:
            for i, w in enumerate(cols):
                row.cells[i].width = Cm(w)
            for c in row.cells:
                for p in c.paragraphs:
                    p.paragraph_format.space_after = Pt(2)
                    p.paragraph_format.space_before = Pt(2)
        # шапку не разрываем со следующей строкой
        doc.add_paragraph().paragraph_format.space_after = Pt(2)

    for blk in CONTRACT:
        kind = blk[0]
        if kind == "title":
            para(blk[1], bold=True, align=WD_ALIGN_PARAGRAPH.CENTER, size=14, space_before=4, space_after=2)
        elif kind == "sub":
            para(blk[1], bold=True, align=WD_ALIGN_PARAGRAPH.CENTER, space_after=8)
        elif kind == "row":
            p = doc.add_paragraph()
            p.paragraph_format.tab_stops.add_tab_stop(Cm(17), WD_TAB_ALIGNMENT.RIGHT)
            p.add_run(blk[1] + "\t" + blk[2])
        elif kind == "note":
            para(blk[1], italic=True, size=9.5, space_after=8)
        elif kind == "h":
            para(blk[1], bold=True, align=WD_ALIGN_PARAGRAPH.CENTER, space_before=10, space_after=4, keep=True)
        elif kind == "p":
            p = para(blk[1], align=WD_ALIGN_PARAGRAPH.JUSTIFY)
        elif kind == "table":
            table(blk[1])
        elif kind == "pagebreak":
            doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)

    # номер страницы в нижнем колонтитуле
    fp = sec.footer.paragraphs[0]
    fp.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = fp.add_run()
    for tag, text in (("begin", None), (None, "PAGE"), ("end", None)):
        if tag:
            el = OxmlElement("w:fldChar")
            el.set(qn("w:fldCharType"), tag)
        else:
            el = OxmlElement("w:instrText")
            el.set(qn("xml:space"), "preserve")
            el.text = text
        run._r.append(el)
    run.font.size = Pt(9)

    doc.core_properties.title = "Договор на изготовление, доставку и установку мебели (шаблон)"
    doc.core_properties.author = "Kitchen Calc"
    doc.save(path)


